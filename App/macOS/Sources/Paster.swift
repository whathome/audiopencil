import APCore
import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Pastes dictated text into the focused field with a synthetic ⌘V.
///
/// With "Keep my clipboard" on, the dictation borrows the clipboard: what was there is saved, the dictation
/// is offered on request (so the paste has to ask for it, which is the main sign it arrived) and marked
/// transient so clipboard managers skip it. Once the paste is confirmed, the saved clipboard goes back.
/// If it can't be confirmed, the dictation stays on the clipboard as a backup, and the saved clipboard
/// goes back after the dictation is pasted by hand, or after a couple of minutes.
@MainActor
final class Paster: NSObject, NSPasteboardItemDataProvider {
    enum Outcome: String {
        /// Seen to arrive (or, with "Keep my clipboard" off, sent).
        case pasted
        /// ⌘V sent, but nothing showed it arrived: the dictation is on the clipboard.
        case unconfirmed
        /// The focus can't take text, so no ⌘V: the dictation is on the clipboard.
        case clipboardOnly
    }

    var keepsClipboard = true

    private let pasteboard = NSPasteboard.general
    /// The user's clipboard, waiting to go back.
    private var saved: ClipboardSnapshot?
    /// The clipboard's change count right after the dictation went on it: anything else means someone
    /// copied since, and their copy wins.
    private var ownChangeCount: Int?
    /// The dictation being offered, and when an app last asked for it.
    private var offered: String?
    private var readAt: ContinuousClock.Instant?
    /// Unconfirmed: put the saved clipboard back once the dictation is pasted by hand, or after a while.
    private var restoresAfterUse = false
    private var restoreTimer: Task<Void, Never>?

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// Roles that definitely can't take pasted text. Anything else (including unknown roles and
    /// apps that don't expose their focus, like many Electron apps) gets the paste.
    private static let nonTextRoles: Set<String> = [
        "AXList", "AXOutline", "AXTable", "AXBrowser", "AXButton", "AXImage", "AXWindow",
        "AXApplication", "AXMenuBar", "AXMenu", "AXMenuItem", "AXCheckBox", "AXRadioButton",
        "AXSlider", "AXScrollBar", "AXToolbar", "AXPopUpButton", "AXDockItem",
    ]

    /// Pastes `text`, calling `posted` as soon as ⌘V is sent (for latency), and returns once the paste is
    /// confirmed or given up on (about a second at most).
    func deliver(_ text: String, posted: () -> Void = {}) async -> Outcome {
        guard keepsClipboard else {
            forgetSaved()
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            guard AXIsProcessTrusted(), let _ = Self.textFocus() else { return .clipboardOnly }
            Self.postCommandV()
            posted()
            return .pasted
        }

        borrowClipboard(for: text)
        guard AXIsProcessTrusted(), let focus = Self.textFocus() else {
            keepAsBackup()
            return .clipboardOnly
        }
        let field = focus.map(FieldReader.init)
        let before = await field?.state()
        Self.postCommandV()
        let sentAt = ContinuousClock.now
        posted()

        // Wait for the app to ask for the text, then give the field a moment to show it.
        var evidence = PasteCheck.Evidence.unknown
        while ContinuousClock.now - sentAt < .milliseconds(1200) {
            try? await Task.sleep(for: .milliseconds(40))
            if offered != text { return .pasted } // a newer dictation took over
            evidence = PasteCheck.evidence(before: before, after: await field?.state(), pasted: text)
            if evidence == .arrived { break }
            if let readAt, ContinuousClock.now - readAt > .milliseconds(350) { break }
        }
        let verdict = PasteCheck.verdict(clipboardRead: readAt != nil, evidence: evidence)
        let waited = ContinuousClock.now - sentAt
        Log.dictation.notice("Paste check after \(waited, privacy: .public): read \(self.readAt.map { "\($0 - sentAt)" } ?? "no", privacy: .public), field \(String(describing: evidence), privacy: .public) (readable \(before?.value != nil || before?.length != nil, privacy: .public)), \(String(describing: verdict), privacy: .public)")
        switch verdict {
        case .confirmed:
            restoreSaved()
            return .pasted
        case .unconfirmed:
            keepAsBackup()
            return .unconfirmed
        }
    }

    /// "Copy Last Dictation": a plain copy the user asked for, so it stays (and clipboard managers keep it).
    func copy(_ text: String) {
        forgetSaved()
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Quitting: an offer can't be kept after the app is gone, so hand over the real text.
    func settle() {
        guard let offered, pasteboard.changeCount == ownChangeCount else { return }
        pasteboard.clearContents()
        pasteboard.setString(offered, forType: .string)
        pasteboard.setData(Data(), forType: Self.transientType)
    }

    // MARK: Clipboard

    private func borrowClipboard(for text: String) {
        restoreTimer?.cancel()
        restoresAfterUse = false
        // Still showing an earlier dictation: the saved clipboard is still the user's, keep it.
        // Otherwise save what's there now.
        if pasteboard.changeCount != ownChangeCount {
            saved = ClipboardSnapshot.capture(pasteboard)
        }
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        item.setData(Data(), forType: Self.transientType)
        item.setString(Bundle.main.bundleIdentifier ?? "", forType: Self.sourceType)
        offered = text
        readAt = nil
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        ownChangeCount = pasteboard.changeCount
    }

    /// The dictation stays on the clipboard; the user's goes back after it's used, or in two minutes.
    private func keepAsBackup() {
        restoresAfterUse = saved != nil
        restoreTimer?.cancel()
        guard saved != nil else { return }
        restoreTimer = Task { [weak self] in
            try? await Task.sleep(for: .seconds(120))
            guard !Task.isCancelled else { return }
            self?.restoreSaved()
        }
    }

    private func restoreSaved() {
        restoreTimer?.cancel()
        restoresAfterUse = false
        defer { forgetSaved() }
        // Someone copied something since: theirs wins.
        guard let saved, pasteboard.changeCount == ownChangeCount else { return }
        saved.restore(to: pasteboard)
        ownChangeCount = nil
        offered = nil
    }

    private func forgetSaved() {
        saved = nil
        restoreTimer?.cancel()
        restoresAfterUse = false
    }

    /// An app asked for the dictation: AppKit calls this on the main thread, while that app waits.
    nonisolated func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        nonisolated(unsafe) let item = item
        MainActor.assumeIsolated {
            guard let offered else { return }
            item.setString(offered, forType: type)
            readAt = .now
            Log.dictation.notice("Clipboard text requested (\(type.rawValue, privacy: .public))")
            // The backup was pasted by hand: the user's clipboard can come back.
            if restoresAfterUse {
                restoresAfterUse = false
                restoreTimer?.cancel()
                restoreTimer = Task { [weak self] in
                    try? await Task.sleep(for: .milliseconds(500))
                    guard !Task.isCancelled else { return }
                    self?.restoreSaved()
                }
            }
        }
    }

    // MARK: Accessibility

    /// The focused element when it might take text: `.some(nil)` when the app doesn't say what's focused
    /// (paste anyway), nil when the focus clearly can't take text.
    private static func textFocus() -> AXUIElement?? {
        let systemWide = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID()
        else {
            return .some(nil) // can't tell; paste anyway
        }
        let element = focused as! AXUIElement
        var role: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &role)
        return nonTextRoles.contains(role as? String ?? "") ? nil : .some(element)
    }


    // MARK: Keys

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = keyCode(producing: "v") ?? 9 // 9 is V on ANSI layouts (US, UK, AZERTY, QWERTZ)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: isDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// The key that types `character` with ⌘ held in the current keyboard layout. Dvorak puts V elsewhere;
    /// "Dvorak – QWERTY ⌘" switches back to QWERTY while ⌘ is down, which translating with ⌘ covers.
    private static func keyCode(producing character: Character) -> CGKeyCode? {
        guard let layoutSource = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let pointer = TISGetInputSourceProperty(layoutSource, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
        return data.withUnsafeBytes { buffer -> CGKeyCode? in
            guard let layout = buffer.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            let commandState = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<CGKeyCode(128) {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout, code, UInt16(kUCKeyActionDisplay), commandState, UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, chars.count, &length, &chars
                )
                if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1).lowercased() == String(character) {
                    return code
                }
            }
            return nil
        }
    }
}

/// Reads the focused field's text off the main thread, with a short timeout. While an app pastes, it waits
/// on Audio Pencil for the clipboard's text; asking that app about its field from the main thread at the
/// same time would leave each waiting on the other until Accessibility gives up.
nonisolated struct FieldReader: @unchecked Sendable {
    private let element: AXUIElement

    init(_ element: AXUIElement) {
        self.element = element
        AXUIElementSetMessagingTimeout(element, 0.25)
    }

    func state() async -> FieldState? {
        await Task.detached(priority: .userInitiated) { () -> FieldState? in
            var value: CFTypeRef?
            var count: CFTypeRef?
            let valueError = AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value)
            let countError = AXUIElementCopyAttributeValue(element, kAXNumberOfCharactersAttribute as CFString, &count)
            guard valueError == .success || countError == .success else { return nil }
            var text = value as? String
            if let current = text, (current as NSString).length > 400_000 { text = nil } // a huge document: length is enough
            return FieldState(value: text, length: count as? Int)
        }.value
    }
}

/// A copy of everything on the clipboard (every item, every type), held in memory only, to put back.
struct ClipboardSnapshot {
    private let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]

    /// Bigger clipboards (a large image, say) are left alone rather than copied.
    static let limit = 32 * 1_000_000

    /// Nil when the clipboard shouldn't or can't be kept: a password (concealed) or other short-lived
    /// content, macOS set to deny Audio Pencil clipboard access, or more than `limit` bytes.
    static func capture(_ pasteboard: NSPasteboard) -> ClipboardSnapshot? {
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny { return nil }
        let types = pasteboard.types ?? []
        // Password managers clear these on a timer; putting one back would keep it around.
        if types.contains(Paster.concealedType) || types.contains(Paster.transientType) { return nil }
        var total = 0
        var items: [[(type: NSPasteboard.PasteboardType, data: Data)]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var pairs: [(type: NSPasteboard.PasteboardType, data: Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > limit { return nil }
                pairs.append((type, data))
            }
            items.append(pairs)
        }
        return ClipboardSnapshot(items: items)
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { pairs in
            let item = NSPasteboardItem()
            for pair in pairs { item.setData(pair.data, forType: pair.type) }
            // Already in clipboard managers' history from when it was copied: don't add it twice.
            item.setData(Data(), forType: Paster.autoGeneratedType)
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}
